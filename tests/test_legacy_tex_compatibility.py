"""Byte-identity guard for the legacy LaTeX output.

The structured CV feature added branches to the four CV templates and extended
the renderer context. Those branches must be inert for legacy CVs.

The fixtures under ``tests/fixtures/legacy_tex_a28d1fd`` were generated by
running the renderer of commit ``a28d1fd`` (the baseline before the feature)
against the fictional legacy CV built by :func:`_build_reference_cv`. The
reference was produced from the baseline code itself, never from the code under
test, so this compares two independent implementations.

The compatibility level asserted here is BYTE IDENTITY: the current renderer
must emit the exact same characters as the baseline, not merely an equivalent
document. That is stronger than textual equivalence and is only meaningful
because neither implementation embeds a timestamp.
"""

import unittest
from pathlib import Path

from app.models import CV
from app.services.latex_service import generate_cv_tex_document

TEMPLATE_KEYS = ("classic", "modern", "compact", "tech")
FIXTURE_DIRECTORY = Path(__file__).parent / "fixtures" / "legacy_tex_a28d1fd"


def _build_reference_cv() -> CV:
    """Fictional legacy CV, built only from flat fields with fixed values.

    Fixed timestamps and a fixed body keep the generated document deterministic.
    The text intentionally includes characters that exercise escaping (``&``,
    accented characters and punctuation) so the guard would notice a change in
    sanitization or encoding.
    """
    return CV(
        id=1,
        title="CV de Referencia",
        full_name="Ana Perez",
        email="ana@example.com",
        phone="+54 11 1234-5678",
        professional_summary=(
            "Desarrolladora backend con foco en APIs. Experiencia con Python, "
            "FastAPI y SQLite. Skills: Python, SQL, LaTeX &amp; Jinja2."
        ),
        experience_summary=(
            "Desarrollo y mantenimiento de APIs REST con FastAPI. "
            "Base de datos SQLite. Automatizacion de deploys."
        ),
        education_summary="Ingenieria en Sistemas. Universidad Nacional.",
        skills="Python, FastAPI, SQLite, LaTeX, Jinja2, Git &amp; Docker",
        created_at="2026-01-01 00:00:00",
        updated_at="2026-01-02 00:00:00",
        deleted_at=None,
    )


def _expected_tex(template_key: str) -> str:
    fixture = FIXTURE_DIRECTORY / f"{template_key}.tex"
    if not fixture.is_file():
        raise AssertionError(f"Falta el fixture de referencia: {fixture}")
    return fixture.read_text(encoding="utf-8")


class LegacyTexCompatibilityTest(unittest.TestCase):
    """The legacy LaTeX path must stay byte-identical to the a28d1fd baseline."""

    def test_all_four_templates_emit_byte_identical_legacy_tex(self) -> None:
        cv = _build_reference_cv()
        differences: list[str] = []

        for template_key in TEMPLATE_KEYS:
            with self.subTest(template=template_key):
                document = generate_cv_tex_document(cv, template_key)
                expected = _expected_tex(template_key)
                if document.content != expected:
                    differences.append(template_key)
                    expected_lines = expected.splitlines()
                    actual_lines = document.content.splitlines()
                    self.assertEqual(
                        len(expected_lines),
                        len(actual_lines),
                        f"{template_key}: cantidad de lineas distinta",
                    )
                    for index, (expected_line, actual_line) in enumerate(
                        zip(expected_lines, actual_lines), start=1
                    ):
                        if expected_line != actual_line:
                            self.fail(
                                f"{template_key}: primera diferencia en la linea "
                                f"{index}\n  esperado: {expected_line!r}\n"
                                f"  actual  : {actual_line!r}"
                            )

        self.assertEqual(differences, [], "plantillas con TEX legacy divergente")

    def test_fixtures_cover_every_template(self) -> None:
        for template_key in TEMPLATE_KEYS:
            with self.subTest(template=template_key):
                fixture = FIXTURE_DIRECTORY / f"{template_key}.tex"
                self.assertTrue(fixture.is_file(), f"falta {fixture}")
                self.assertGreater(len(fixture.read_text(encoding="utf-8")), 0)

    def test_generated_document_does_not_embed_a_timestamp(self) -> None:
        """Guarantees byte identity stays a meaningful assertion.

        If the renderer ever embeds the current time, two runs of the same
        legacy CV would differ and the guard above would fail for the wrong
        reason. This test names that risk explicitly instead of hiding it.
        """
        cv = _build_reference_cv()
        first = generate_cv_tex_document(cv, "classic").content
        second = generate_cv_tex_document(cv, "classic").content
        self.assertEqual(first, second, "el render legacy no es determinista")

    def test_structured_only_fields_are_absent_from_legacy_tex(self) -> None:
        """Legacy output must not leak structured-only concepts."""
        document = generate_cv_tex_document(_build_reference_cv(), "classic").content
        for marker in ("\\Needspace", "\\allowbreak", "structured"):
            with self.subTest(marker=marker):
                self.assertNotIn(marker, document)


if __name__ == "__main__":
    unittest.main()